// Generates src/components/icons.tsx: the lucide-react names this app imports, drawn with
// Looseleaf's hand-drawn Icon where one exists, and lucide's own icon where it does not.
// Run: node scripts/gen-ink-icons.mjs (after adding a new lucide import, run it again).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const src = path.join(root, 'src');
const iconDir = path.join(src, 'lib/ink/art/icons');

const drawn = new Set();
for (const f of fs.readdirSync(iconDir)) {
  const text = fs.readFileSync(path.join(iconDir, f), 'utf8');
  for (const m of text.matchAll(/^\s*['"]?([a-z][a-z0-9-]*)['"]?:\s*\{/gm)) drawn.add(m[1]);
}
const aliases = fs.readFileSync(path.join(iconDir, 'aliases.ts'), 'utf8');
for (const m of aliases.matchAll(/"([a-z0-9-]+)":\s*\[([^\]]*)\]/g)) {
  if (!drawn.has(m[1])) continue;
  for (const a of m[2].matchAll(/"([a-z0-9-]+)"/g)) drawn.add(a[1]);
}

const used = new Set();
const walk = dir => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.tsx?$/.test(e.name) && !p.endsWith(path.join('components', 'icons.tsx'))) {
      const text = fs.readFileSync(p, 'utf8');
      for (const m of text.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"](?:lucide-react|@\/components\/icons)['"]/g)) {
        for (const raw of m[1].split(',')) {
          const name = raw.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0].trim();
          if (name && /^[A-Z]/.test(name) && !['LucideIcon', 'LucideProps'].includes(name)) used.add(name);
        }
      }
    }
  }
};
walk(src);

const kebab = name => name
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/([A-Za-z])([0-9])/g, '$1-$2')
  .toLowerCase();

// Lucide icons with no drawn twin, mapped to the nearest drawn one.
const NEAREST = {
  Activity: 'chart-line', BookPlus: 'book-open', ChartNoAxesColumn: 'chart-column', Code2: 'code',
  Expand: 'frame', FileCheck2: 'file-text', Gauge: 'timer', Link2: 'link', Maximize: 'frame',
  MessageSquareHeart: 'message-square', MessageSquareWarning: 'message-square', NotebookPen: 'pencil',
  PanelRightClose: 'panel-left-close', PanelRightOpen: 'panel-left-open', PenLine: 'pencil',
  RefreshCw: 'rotate-cw', RotateCcw: 'undo-2', Route: 'map', SendHorizontal: 'send', Share2: 'share',
  ShieldOff: 'shield-alert', SquareCode: 'square-terminal', SquarePen: 'pencil', SquarePlus: 'circle-plus',
  Target: 'circle-dot', Trophy: 'star', XCircle: 'circle-x', Building2: 'layout-grid', Hammer: 'settings-2',
  CloudOff: 'cloud', Flame: 'sparkles', Shapes: 'layout-grid', Sigma: 'calculator', FlaskConical: 'lightbulb',
};
const lines = [];
let inked = 0;
for (const name of [...used].sort()) {
  const id = NEAREST[name] ?? kebab(name);
  if (drawn.has(id)) { lines.push(`export const ${name} = ink('${id}');`); inked++; }
  else lines.push(`export const ${name} = Lucide.${name};`);
}

const out = `'use client';
// Generated by scripts/gen-ink-icons.mjs. Do not edit by hand.
// Every icon the app uses, by its lucide name: hand-drawn by Looseleaf where it has one.
import * as Lucide from 'lucide-react';
import type { LucideIcon, LucideProps } from 'lucide-react';
import { Icon } from '@/components/ui/icon';

// Only the name is kept: a lucide fallback here would ship every replaced lucide icon too.
function ink(name: string): LucideIcon {
  function Drawn({ size, strokeWidth: _s, absoluteStrokeWidth: _a, color, style, ...props }: LucideProps) {
    void _s; void _a;
    return (
      <Icon
        name={name}
        size={typeof size === 'number' ? size : undefined}
        style={color ? { color, ...style } : style}
        {...(props as Omit<React.ComponentProps<typeof Icon>, 'name'>)}
      />
    );
  }
  Drawn.displayName = \`Ink(\${name})\`;
  return Drawn as unknown as LucideIcon;
}

${lines.join('\n')}

export type { LucideIcon, LucideProps };
`;
fs.writeFileSync(path.join(src, 'components/icons.tsx'), out);
console.log(`${used.size} icons, ${inked} hand-drawn, ${used.size - inked} from lucide`);
